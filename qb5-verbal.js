// QB5 verbal construct variants: 7 families × 2 reasoning archetypes.
(() => {
  'use strict';
  const E=window.QB5E;if(!E)return;const {register,set}=E;
  const scenes=[
    ['館員','借書','借閱證','圖書館'],['園丁','澆花','工作證','溫室'],['旅客','搭車','車票','車站'],['演員','登台','通行證','劇院'],
    ['學員','入場練習','預約單','球館'],['訪客','參觀','入場券','展館'],['技師','維修','工單','工坊'],['讀者','取書','領取單','書店'],
    ['船員','出港','許可證','碼頭'],['廚師','進入備餐區','工作證','廚房'],['畫家','布展','核准單','畫廊'],['登山客','進山','登記證','登山口']
  ];
  const objects=['筆記','雨傘','地圖','外套','相機','手冊'];
  register('necessary-condition',(q,{n,v})=>{
    const [who,act,permit,place]=scenes[n%12];
    if(v===0){q.q=`${place}規定：要取得${act}資格，必須持有${permit}。一位${who}沒有${permit}。依規定，哪一項必然成立？`;set(q,`這位${who}不具備${act}資格`,[`這位${who}一定會${act}`,`這位${who}只要申請就有資格`,`所有${who}都不具備${act}資格`]);q.e=`${permit}是取得${act}資格的必要條件；缺少必要條件，只能推出此人不具備該資格。`;}
    else {const extra=['預約','安全訓練','身分確認'][n%3];q.q=`${place}規定：取得${act}資格必須同時完成「持有${permit}」與「${extra}」。一位${who}已有${permit}，但尚未完成${extra}。哪一項必然成立？`;set(q,`這位${who}目前不具備${act}資格`,[`這位${who}已具備${act}資格`,`${permit}在這裡不是必要條件`,`${extra}完成後一定會實際${act}`]);q.e='兩個條件都被規定為必要；少其中一個就尚未取得資格。';}
  });
  register('reported-vs-fact',(q,{n,v})=>{
    const [who,act,,place]=scenes[n%12];
    if(v===0){q.q=`${place}紀錄寫道：「幾位${who}表示明天打算${act}。」只依這份紀錄，哪一句沒有把「打算」升級成已發生的事？`;set(q,`這幾位${who}表示打算${act}`,[`這幾位${who}已完成${act}`,`明天一定會有人${act}`,`所有${who}都會${act}`]);q.e='紀錄直接支持的是「有人表達打算」；不能因此斷言行動已完成或必然發生。';}
    else {q.q=`一份${place}公告寫道：「主辦方預測明天可能有${who}${act}。」下面哪一句最忠實保留原文的證據強度？`;set(q,`主辦方預測明天可能有${who}${act}`,[`明天確定有${who}${act}`,`今天已經有${who}${act}`,`所有${who}都被要求${act}`]);q.e='「預測」「可能」都表示不確定性；忠實轉述不能把它改成確定事實。';}
  });
  register('contrast-focus',(q,{n,v})=>{
    const opts=[['雨衣','輕巧','防水'],['背包','外型','耐用'],['地圖','精美','準確'],['座椅','便宜','舒適'],['路線','短','安全'],['工具','新穎','實用']];
    const [obj,a,b]=opts[n%opts.length];
    if(v===0){q.q=`小岑說：「${obj}的${a}固然加分，但如果只能優先一項，我會選${b}。」哪一項最符合她的優先順序？`;set(q,`優先考量${b}`,[`只考量${a}`,`${a}與${b}完全同等`,`完全不在乎${a}`]);q.e=`「如果只能優先一項」明確把${b}放在較高順位，但沒有否定${a}的價值。`;}
    else {q.q='小岑比較兩個方案後說：「甲方案更快；乙方案較慢，不過失誤率更低。這次我寧願慢一點。」她最後偏向哪個理由？';set(q,'較低的失誤率',['較快的完成速度','兩方案速度相同','只因為乙方案較新']);q.e='「寧願慢一點」表示她願意犧牲速度，換取乙方案較低的失誤率。';}
  });
  register('scope-negation',(q,{n,v})=>{
    const [,act,,place]=scenes[n%12];
    if(v===0){q.q=`針對${place}的受訪者，「並非每個人都願意${act}」與哪一句邏輯上等價？`;set(q,`至少有受訪者不願意${act}`,[`所有受訪者都不願意${act}`,`大多數受訪者不願意${act}`,`恰好一位受訪者願意${act}`]);q.e='否定「每個人都願意」只需要至少一個反例。';}
    else {q.q='句子「不是所有完成 A 的人都完成 B」最合理的等價敘述是？';set(q,'至少有完成 A 的人沒有完成 B',['完成 A 的人全都沒有完成 B','完成 B 的人都完成 A','只有一人同時完成 A 與 B']);q.e='「不是所有 A 都是 B」等價於「存在至少一個 A 不是 B」。';}
  });
  register('instruction-exception',(q,{n,v})=>{
    const [,,,place]=scenes[n%12];
    if(v===0){q.q=`${place}規則：「週末不受理申請；已預約者例外，可在週六辦理。」小禾已預約週六。依規則，哪項成立？`;set(q,'小禾可在預約的週六辦理',['小禾只能改到週日辦理','所有人週六都能辦理','預約者週日也一定能辦理']);q.e='一般規則禁止週末，但已預約者有明示的週六例外。';}
    else {q.q='某場館規則：「飲料不得帶入展間；密封飲用水除外。玻璃瓶即使密封也不得帶入。」小禾帶的是密封塑膠瓶裝水。依規則，哪項成立？';set(q,'可以帶入展間',['任何飲料都不可帶入','只有玻璃瓶裝水可以帶入','密封飲用水也一律禁止']);q.e='密封飲用水屬於例外；玻璃瓶的再例外只排除玻璃瓶，不影響塑膠瓶。';}
  });
  register('pronoun-reference',(q,{n,v})=>{
    const obj=objects[n%objects.length];
    if(v===0){q.q=`小禾把${obj}交給小安，並對小安說：「請你明天把它帶回來。」句中的「你」指誰？`;set(q,'小安',['小禾','兩人都是','無法由句子判斷']);q.e='直接引語中的「你」指說話者正在對話的對象；小禾正在對小安說話。';}
    else {q.q=`小安對小禾說：「我會先整理${obj}，你再把它放回櫃子。」句中的「它」指什麼？`;set(q,obj,['小安','小禾','櫃子']);q.e=`「它」承接前一句剛提到、可被放回櫃子的物件：${obj}。`;}
  });
  register('evidence-strength',(q,{n,v})=>{
    const [,act,,place]=scenes[n%12];
    if(v===0){q.q=`一份調查只訪問${place}的幾位常客，結果所有受訪者都表示喜歡${act}。哪個結論得到這份資料直接支持？`;set(q,`受訪常客一致表示喜歡${act}`,[`全城居民一致表示喜歡${act}`,`${act}讓每個人更快樂`,`不常來的人大多討厭${act}`]);q.e='樣本資料能直接支持受訪者本身的回答，不能自動外推到未受訪者或推出因果。';}
    else {q.q='觀察資料顯示：在這批受測者中，睡眠時間較長的人平均分數也較高。僅憑這項觀察，哪個說法最穩妥？';set(q,'這批資料中睡眠時間與分數呈現關聯',['增加睡眠一定會提高每個人的分數','分數高一定是睡眠較長造成的','沒有其他因素可能同時影響兩者']);q.e='觀察到的是關聯，不足以單獨證明因果方向或排除其他因素。';}
  });
})();